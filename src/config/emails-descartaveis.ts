/** O e-mail é de um domínio descartável da lista (ou de um subdomínio dele)? Recebe o e-mail inteiro. */
export function emailEhDescartavel(email: string): boolean {
  const dominio = email.trim().toLowerCase().split("@").pop() ?? "";
  if (!dominio.includes(".")) return false;
  return DOMINIOS_DESCARTAVEIS.some((descartavel) => dominio === descartavel || dominio.endsWith(`.${descartavel}`));
}
